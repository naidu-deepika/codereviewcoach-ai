function lineText(f) {
  if (!f.line_start) return 'not specified'
  if (f.line_end && f.line_end !== f.line_start) return `${f.line_start}-${f.line_end}`
  return String(f.line_start)
}

export function buildMarkdown(result, originalCode) {
  const date = new Date().toISOString().slice(0, 10)
  const hasScore = typeof result.score === 'number'
  const out = []

  out.push('# CodeReviewCoach-AI review report', '')
  out.push(`- Language: ${result.language}`)
  out.push(`- Date: ${date}`)
  if (hasScore) out.push(`- Quality score: ${result.score}/100`)
  out.push('', '## Summary', '', result.summary, '')

  if (hasScore) {
    out.push('## How the score was calculated', '')
    result.score_details.forEach((d) => out.push(`- ${d}`))
    out.push('', '_The score is an estimate based on the findings. It does not prove the code is correct._', '')
  }

  out.push(`## Findings (${result.findings.length})`, '')
  if (result.findings.length === 0) {
    out.push('No issues were found in this review. This does not prove the code is correct.', '')
  }
  result.findings.forEach((f, i) => {
    const kind = f.source === 'static_analysis' ? 'Verified check' : 'AI suggestion'
    out.push(`### ${i + 1}. ${f.message}`, '')
    out.push(`- Type: ${kind}`)
    out.push(`- Severity: ${f.severity}`)
    out.push(`- Category: ${f.category}`)
    out.push(`- Line: ${lineText(f)}`)
    out.push('', f.explanation, '')
    if (f.suggested_fix) out.push(`**Fix:** ${f.suggested_fix}`, '')
  })

  out.push('## Original code', '', '````python', originalCode, '````', '')

  if (result.corrected_code) {
    out.push('## Suggested corrected code', '', '````python', result.corrected_code, '````', '')
    out.push('_AI-generated corrections may need testing._', '')
  }

  if (result.verification?.performed) {
    out.push('## Recheck of the corrected code', '')
    result.verification.checks.forEach((c) => out.push(`- ${c}`))
    out.push('')
  }

  out.push(
    '---',
    '_Generated by CodeReviewCoach-AI. Verified checks come from static analysis. AI suggestions are opinions and may be wrong._'
  )
  return out.join('\n')
}

export function downloadMarkdown(result, originalCode) {
  const blob = new Blob([buildMarkdown(result, originalCode)], {
    type: 'text/markdown;charset=utf-8',
  })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `code-review-${new Date().toISOString().slice(0, 10)}.md`
  document.body.appendChild(a)
  a.click()
  a.remove()
  URL.revokeObjectURL(url)
}
